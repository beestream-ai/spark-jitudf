package ai.beestream.jitudf;

import ai.rapids.cudf.DType;
import org.apache.spark.sql.types.DataType;
import org.apache.spark.sql.types.DataTypes;

import uk.ac.manchester.tornado.api.types.arrays.DoubleArray;
import uk.ac.manchester.tornado.api.types.arrays.FloatArray;
import uk.ac.manchester.tornado.api.types.arrays.IntArray;
import uk.ac.manchester.tornado.api.types.arrays.LongArray;
import uk.ac.manchester.tornado.api.types.arrays.TornadoNativeArray;

/**
 * The fixed-width numeric types this integration carries end to end: a Spark {@link DataType}, the
 * cuDF {@link DType} its column has, the Java primitive the user's UDF works in, and the TornadoVM
 * native array a device view of that column binds to.
 *
 * <p>
 * Everything outside this list -- strings, decimals, booleans, dates, nested types other than the
 * {@code LIST} of one of these -- is rejected at planning time rather than approximated.
 * </p>
 */
public enum PrimitiveKind {

    INT(DataTypes.IntegerType, DType.INT32, int.class, Integer.class, IntArray.class, "I", 4),
    LONG(DataTypes.LongType, DType.INT64, long.class, Long.class, LongArray.class, "J", 8),
    FLOAT(DataTypes.FloatType, DType.FLOAT32, float.class, Float.class, FloatArray.class, "F", 4),
    DOUBLE(DataTypes.DoubleType, DType.FLOAT64, double.class, Double.class, DoubleArray.class, "D", 8);

    private final DataType sparkType;
    private final DType cudfType;
    private final Class<?> primitiveClass;
    private final Class<?> boxedClass;
    private final Class<? extends TornadoNativeArray> arrayClass;
    private final String descriptor;
    private final int byteWidth;

    PrimitiveKind(DataType sparkType, DType cudfType, Class<?> primitiveClass, Class<?> boxedClass, Class<? extends TornadoNativeArray> arrayClass, String descriptor, int byteWidth) {
        this.sparkType = sparkType;
        this.cudfType = cudfType;
        this.primitiveClass = primitiveClass;
        this.boxedClass = boxedClass;
        this.arrayClass = arrayClass;
        this.descriptor = descriptor;
        this.byteWidth = byteWidth;
    }

    public DataType sparkType() {
        return sparkType;
    }

    public DType cudfType() {
        return cudfType;
    }

    public Class<?> primitiveClass() {
        return primitiveClass;
    }

    public Class<?> boxedClass() {
        return boxedClass;
    }

    public Class<? extends TornadoNativeArray> arrayClass() {
        return arrayClass;
    }

    /** The JVM field descriptor of the primitive, e.g. {@code D} for a double. */
    public String descriptor() {
        return descriptor;
    }

    public int byteWidth() {
        return byteWidth;
    }

    /** How many JVM local-variable slots a value of this type occupies. */
    public int slots() {
        return byteWidth == 8 ? 2 : 1;
    }

    /** The internal name of the TornadoVM array class, for generated bytecode. */
    public String arrayInternalName() {
        return arrayClass.getName().replace('.', '/');
    }

    public static PrimitiveKind ofSparkType(DataType type) {
        for (PrimitiveKind kind : values()) {
            if (kind.sparkType.equals(type)) {
                return kind;
            }
        }
        return null;
    }

    /** The kind a Java parameter or return type stands for, boxed or not; {@code null} if none. */
    public static PrimitiveKind ofJavaType(Class<?> type) {
        for (PrimitiveKind kind : values()) {
            if (kind.primitiveClass == type || kind.boxedClass == type) {
                return kind;
            }
        }
        return null;
    }

    /** The kind a Java primitive array's component type stands for; {@code null} if none. */
    public static PrimitiveKind ofArrayComponent(Class<?> arrayType) {
        if (arrayType == null || !arrayType.isArray()) {
            return null;
        }
        Class<?> component = arrayType.getComponentType();
        for (PrimitiveKind kind : values()) {
            if (kind.primitiveClass == component) {
                return kind;
            }
        }
        return null;
    }

    /** The JVM opcode that loads an element of this kind from a Java array. */
    public int arrayLoadOpcode() {
        return switch (this) {
            case INT -> org.objectweb.asm.Opcodes.IALOAD;
            case LONG -> org.objectweb.asm.Opcodes.LALOAD;
            case FLOAT -> org.objectweb.asm.Opcodes.FALOAD;
            case DOUBLE -> org.objectweb.asm.Opcodes.DALOAD;
        };
    }

    public static PrimitiveKind ofCudfType(DType type) {
        for (PrimitiveKind kind : values()) {
            if (kind.cudfType.equals(type)) {
                return kind;
            }
        }
        return null;
    }
}
