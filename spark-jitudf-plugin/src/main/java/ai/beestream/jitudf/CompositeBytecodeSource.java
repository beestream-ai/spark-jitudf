package ai.beestream.jitudf;

import java.io.InputStream;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Optional;

import uk.ac.manchester.tornado.tc.frontend.Frontend;

/**
 * Where TC reads class bytes from while compiling one UDF on the driver.
 *
 * <p>
 * TC never loads a class: it parses bytes. That is the property this whole architecture rests on,
 * because it means the driver compiles a UDF without running its static initialiser, without
 * needing TornadoVM's runtime, and without a GPU. What it does need is an answer to "give me the
 * bytes of this internal name", for the generated entry class, for the user's UDF class and its
 * helpers, and for whatever JDK classes those reach.
 * </p>
 *
 * <p>
 * The three sources are tried in order, and the order matters. Generated bytes come first because
 * the entry class exists nowhere else. The UDF's own loader comes next, because in a Spark job that
 * is the loader holding the user's jar. The platform loader is last and is what makes
 * {@code Long.bitCount} and {@code Math.floorMod} reachable: TC follows a call it does not
 * recognise by reading the callee's bytecode, so a {@code java.base} method compiles from the JDK's
 * own implementation rather than needing an entry in TC's intrinsic table.
 * </p>
 */
public final class CompositeBytecodeSource implements Frontend.BytecodeSource {

    private final Map<String, byte[]> generated = new LinkedHashMap<>();
    private final ClassLoader userLoader;

    /**
     * @param userLoader
     *         the loader that defined the UDF's class, or null to use this class's own.
     */
    public CompositeBytecodeSource(ClassLoader userLoader) {
        this.userLoader = userLoader == null ? CompositeBytecodeSource.class.getClassLoader() : userLoader;
    }

    /** Adds bytes that exist only in memory, keyed by internal name ({@code pkg/Name}). */
    public CompositeBytecodeSource with(String internalName, byte[] classFile) {
        generated.put(internalName, classFile);
        return this;
    }

    @Override
    public Optional<byte[]> classBytes(String internalName) {
        byte[] inMemory = generated.get(internalName);
        if (inMemory != null) {
            return Optional.of(inMemory);
        }
        String resource = internalName + ".class";
        Optional<byte[]> fromUser = read(userLoader, resource);
        if (fromUser.isPresent()) {
            return fromUser;
        }
        // java.base and the rest of the platform. Its classes are not visible through an ordinary
        // application loader's parent in every embedding, so ask for them explicitly.
        return read(ClassLoader.getPlatformClassLoader(), resource);
    }

    private static Optional<byte[]> read(ClassLoader loader, String resource) {
        if (loader == null) {
            return Optional.empty();
        }
        try (InputStream in = loader.getResourceAsStream(resource)) {
            return in == null ? Optional.empty() : Optional.of(in.readAllBytes());
        } catch (Exception e) {
            return Optional.empty();
        }
    }
}
