package io.github.beehivelab.jitudf;

import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.List;

import uk.ac.manchester.tornado.api.TaskGraph;
import uk.ac.manchester.tornado.api.TornadoExecutionPlan;
import uk.ac.manchester.tornado.api.TornadoExecutionResult;
import uk.ac.manchester.tornado.api.enums.ProfilerMode;
import uk.ac.manchester.tornado.api.types.arrays.DoubleArray;
import uk.ac.manchester.tornado.api.types.arrays.FloatArray;
import uk.ac.manchester.tornado.api.types.arrays.IntArray;
import uk.ac.manchester.tornado.api.types.arrays.LongArray;
import uk.ac.manchester.tornado.api.types.arrays.TornadoNativeArray;

/**
 * One UDF's compiled kernel, its device views and its reusable execution plan, held for the life of
 * a Spark task.
 *
 * <p>
 * The views and the plan are built once and rebound per batch: only the bound addresses change, and
 * the device views carry no length precisely so that rebinding them does not key a new compilation.
 * The row count is a task argument and therefore fixed in the task graph, so there is one of these
 * per distinct batch size; TornadoVM generalises its compiled kernel over a scalar that has taken a
 * few different values, so a handful of batch sizes still share one piece of native code.
 * </p>
 *
 * <p>
 * Not thread-safe, and deliberately so: a view may be bound by one plan at a time, so one of these
 * belongs to one task. {@link TornadoKernelCache} keeps them per thread.
 * </p>
 */
final class KernelExecution implements AutoCloseable {

    private final KernelDescriptor descriptor;
    private final List<TornadoNativeArray> inputViews = new ArrayList<>();
    private final TornadoNativeArray outputView;
    private final TornadoExecutionPlan plan;
    private final int numRows;
    private final long listValueCapacity;
    private final int cudaOrdinal;

    private boolean bound;

    /** {@code -Dtornado.spark.profile=true} measures the device transfers and the kernel time. */
    static final boolean PROFILE = Boolean.getBoolean("tornado.spark.profile");

    private volatile long lastCopyInBytes = -1;
    private volatile long lastCopyOutBytes = -1;
    private volatile long lastKernelNanos = -1;
    // TornadoVM's own breakdown of what happens inside execute(). The goal's "kernel compilation
    // and CUDA module loading" is two different compilers: TornadoVM's own compiler TC lowers the
    // generated bytecode to PTX, then the CUDA driver assembles PTX to cubin and loads the module. Both happen lazily on
    // a plan's first execution, so without these they hide inside the first batch's execute time.
    private volatile long lastTornadoCompilerNanos = -1;
    private volatile long lastDriverInstallNanos = -1;
    private volatile long lastDispatchNanos = -1;

    KernelExecution(KernelDescriptor descriptor, Class<?> kernelClass, int numRows, long listValueCapacity, int cudaOrdinal) {
        this.descriptor = descriptor;
        this.numRows = numRows;
        this.listValueCapacity = listValueCapacity;
        this.cudaOrdinal = cudaOrdinal;

        List<Object> taskArguments = new ArrayList<>();
        // A LIST argument is two views: the offsets, which hold one more element than there are
        // rows, and the flattened child, whose capacity is not known until a batch is bound. The
        // capacity is sized for the worst case the kernel could index -- see listValueCapacity.
        for (InputSpec input : descriptor.inputs()) {
            if (input.isList()) {
                TornadoNativeArray offsets = deviceView(PrimitiveKind.INT, numRows + 1);
                TornadoNativeArray values = deviceView(input.kind(), listValueCapacity);
                inputViews.add(offsets);
                inputViews.add(values);
                taskArguments.add(offsets);
                taskArguments.add(values);
            } else {
                TornadoNativeArray view = deviceView(input.kind(), numRows);
                inputViews.add(view);
                taskArguments.add(view);
            }
        }
        this.outputView = deviceView(descriptor.outputKind(), numRows);
        taskArguments.add(outputView);
        taskArguments.add(numRows);

        Method kernelMethod = findKernelMethod(kernelClass, descriptor);
        this.plan = TornadoContext.call(() -> {
            TaskGraph graph = new TaskGraph("tornado-udf-" + descriptor.udfName()) //
                    .task("udf", kernelMethod, taskArguments.toArray());
            TornadoExecutionPlan built = new TornadoExecutionPlan(graph.snapshot());
            // Strict floating point, always. By default the CUDA backend contracts a*b+c into a
            // fused multiply-add, which rounds once instead of twice. That is more accurate in
            // isolation and still wrong here: this kernel is supposed to compute what the UDF
            // computes on the JVM, and a UDF that branches on `a*b+c == 0` takes the other branch
            // under contraction. A difference in the last bits of a sum is tolerable; a different
            // branch is a different answer.
            built = built.withStrictFloatingPoint();
            // And on the GPU cuDF is on. See DeviceAffinity: TornadoVM's default device is not
            // necessarily the device whose pointers this kernel is about to be handed.
            built = built.withDevice(DeviceAffinity.forCudaOrdinal(cudaOrdinal));
            // The profiler is what turns "there is no copy" from a claim about the code into a
            // measurement: it counts the bytes TornadoVM moved, which for device-view arguments
            // must be zero. It costs a little per execution, so it is opt-in.
            return PROFILE ? built.withProfiler(ProfilerMode.SILENT) : built;
        });
    }

    private static Method findKernelMethod(Class<?> kernelClass, KernelDescriptor descriptor) {
        for (Method method : kernelClass.getDeclaredMethods()) {
            if (method.getName().equals(descriptor.kernelMethodName())) {
                return method;
            }
        }
        throw new IllegalStateException("the generated class " + kernelClass.getName() + " has no " + descriptor.kernelMethodName() + " method");
    }

    private static TornadoNativeArray deviceView(PrimitiveKind kind, long rows) {
        return switch (kind) {
            case INT -> IntArray.deviceView(rows);
            case LONG -> LongArray.deviceView(rows);
            case FLOAT -> FloatArray.deviceView(rows);
            case DOUBLE -> DoubleArray.deviceView(rows);
        };
    }

    int numRows() {
        return numRows;
    }

    /** The CUDA ordinal this execution's plan was pinned to. */
    int cudaOrdinal() {
        return cudaOrdinal;
    }

    /** How many list elements this execution's child views can address. */
    long listValueCapacity() {
        return listValueCapacity;
    }

    KernelDescriptor descriptor() {
        return descriptor;
    }

    /**
     * Points the views at this batch's buffers, in the order the kernel takes them (a LIST argument
     * contributing its offsets then its values). Replaces whatever the previous batch bound.
     */
    void bind(List<CudfBufferAdapter.InputBinding> inputs, long outputAddress, long outputByteLength) {
        if (inputs.size() != inputViews.size()) {
            throw new IllegalStateException("the kernel takes " + inputViews.size() + " input views but " + inputs.size() + " bindings were given");
        }
        unbind();
        int boundSoFar = 0;
        try {
            for (int i = 0; i < inputs.size(); i++) {
                CudfBufferAdapter.InputBinding input = inputs.get(i);
                plan.bindExternalBuffer(inputViews.get(i), input.address(), input.byteLength(), input.rows(), -1, true);
                boundSoFar++;
            }
            plan.bindExternalBuffer(outputView, outputAddress, outputByteLength, numRows, -1, false);
        } catch (RuntimeException e) {
            // Binding is all or nothing. A view left bound by a half-finished attempt keeps an
            // address the caller is about to release, and the ownership token with it, so the next
            // batch cannot bind that view at all.
            for (int i = 0; i < boundSoFar; i++) {
                try {
                    plan.unbindExternalBuffer(inputViews.get(i));
                } catch (RuntimeException ignored) {
                    // Keep unwinding; the original failure is the one worth reporting.
                }
            }
            throw e;
        }
        bound = true;
    }

    void unbind() {
        if (!bound) {
            return;
        }
        for (TornadoNativeArray view : inputViews) {
            plan.unbindExternalBuffer(view);
        }
        plan.unbindExternalBuffer(outputView);
        bound = false;
    }

    /** Runs the kernel over this execution's row count. */
    void execute() {
        TornadoContext.run(() -> {
            TornadoExecutionResult result = plan.execute();
            if (PROFILE) {
                lastCopyInBytes = result.getProfilerResult().getTotalBytesCopyIn();
                lastCopyOutBytes = result.getProfilerResult().getTotalBytesCopyOut();
                lastKernelNanos = result.getProfilerResult().getDeviceKernelTime();
                lastTornadoCompilerNanos = result.getProfilerResult().getTornadoCompilerTime();
                lastDriverInstallNanos = result.getProfilerResult().getDriverInstallTime();
                lastDispatchNanos = result.getProfilerResult().getKernelDispatchTime();
            }
        });
    }

    /** Bytes TornadoVM copied host-to-device for the last execution, or -1 when not profiling. */
    long lastCopyInBytes() {
        return lastCopyInBytes;
    }

    long lastCopyOutBytes() {
        return lastCopyOutBytes;
    }

    /** Device kernel time of the last execution in nanoseconds, or -1 when not profiling. */
    long lastKernelNanos() {
        return lastKernelNanos;
    }

    /** TC's lowering of the generated bytecode to PTX, or -1 when not profiling. */
    long lastTornadoCompilerNanos() {
        return lastTornadoCompilerNanos;
    }

    /** PTX to cubin plus the CUDA module load, or -1 when not profiling. */
    long lastDriverInstallNanos() {
        return lastDriverInstallNanos;
    }

    /** Kernel launch dispatch, or -1 when not profiling. */
    long lastDispatchNanos() {
        return lastDispatchNanos;
    }

    TornadoExecutionPlan plan() {
        return plan;
    }

    List<TornadoNativeArray> inputViews() {
        return inputViews;
    }

    TornadoNativeArray outputView() {
        return outputView;
    }

    @Override
    public void close() {
        unbind();
        try {
            plan.close();
        } catch (Exception e) {
            throw new IllegalStateException("could not release the execution plan for " + descriptor.udfName(), e);
        }
    }
}
